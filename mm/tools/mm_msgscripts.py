"""MM's message scripts from a decomp actor's file, as C for our port (z_nv_mm_msgevent.c).

MM's people talk through MsgScript arrays written in their actor's file with MSCRIPT_CMD_* macros
(the decomp's include/z64msgevent.h, ours soh/include/z_nv_mm_msgevent.h). Copied as they are,
except that the names they use (week events, Bombers' Notebook events, items, get-items, masks,
item actions) are turned into MM's numbers from the decomp's headers, so the port needs none of
MM's headers. Numbers stay MM's: the interpreter knows they're MM's (week events are Termina's;
items and get-items are MM's ids, see z_nv_mm_msgevent.c).

    mm_msgscripts.py <mm decomp> <actor .c> <out .inc>
"""

import os
import re
import sys


def _enum_values(path):
    """Every `/* 0xNN */ NAME,` (or decimal) in a decomp header: the decomp numbers its enums so."""
    out = {}
    for m in re.finditer(r"/\*\s*(-?0x[0-9A-Fa-f]+|-?\d+)\s*\*/\s*(\w+)\s*[,=]", open(path, errors="replace").read()):
        out.setdefault(m.group(2), int(m.group(1), 0))
    return out


def names(decomp):
    inc = os.path.join(decomp, "include")
    table = {}
    for m in re.finditer(r"#define (WEEKEVENTREG_\w+)\s+PACK_WEEKEVENTREG_FLAG\((\d+), (0x\w+)\)",
                         open(os.path.join(inc, "z64save.h")).read()):
        table[m.group(1)] = (int(m.group(2)) << 8) | int(m.group(3), 16)
    for line in open(os.path.join(inc, "tables", "notebook_table.h")):  # people's "met" first, then events
        m = re.search(r"/\* 0x(\w+) \*/ DEFINE_(?:PERSON\(\w+, \w+, \w+, (\w+)|EVENT\((\w+))", line)
        if m:
            table[m.group(2) or m.group(3)] = int(m.group(1), 16)
    for h in ("z64item.h", "z64player.h"):
        for k, v in _enum_values(os.path.join(inc, h)).items():
            if re.match(r"(ITEM_|GI_|PLAYER_MASK_|PLAYER_IA_|PLAYER_FORM_|QUEST_)", k):
                table.setdefault(k, v)
    return table


def extract(decomp, src):
    table = names(decomp)
    text = open(src).read()
    blocks = re.findall(r"^(?:static )?MsgScript (\w+)\[\] = \{(.*?)^\};", text, re.S | re.M)
    out, missing = [], set()
    for name, body in blocks:
        def sub(m):
            w = m.group(0)
            if w in table:
                return f"0x{table[w]:X}"
            if re.match(r"(WEEKEVENTREG_|BOMBERS_NOTEBOOK_|ITEM_|GI_|PLAYER_MASK_|PLAYER_IA_|QUEST_)", w):
                missing.add(w)
            return w
        body = re.sub(r"\b[A-Z][A-Z0-9_]+\b", sub, body)
        out.append(f"static MsgScript {name}[] = {{{body}}};\n")
    if missing:
        sys.exit(f"names not found in the decomp's headers: {sorted(missing)}")
    return out


def main():
    decomp, src, dest = sys.argv[1:]
    lines = [f"/* Generated by mm/tools/mm_msgscripts.py from the MM decomp's {os.path.relpath(src, decomp)}:",
             " * MM's message scripts, MM's names as MM's numbers. Do not edit. */", ""]
    lines += extract(decomp, src)
    open(dest, "w").write("\n".join(lines))
    print(dest, len(lines) - 3, "scripts")


if __name__ == "__main__":
    main()
