#!/usr/bin/env python3
"""Register MM's converted scenes with Ship of Harkinian's scene and entrance tables.

Writes the two X-macro fragments scene_table.h and entrance_table.h include after RE1's:

    soh/include/tables/nv_mm_scene_table.h      one DEFINE_SCENE per scene
    soh/include/tables/nv_mm_scene_range.h      SCENE_MM_FIRST / SCENE_MM_LAST (NvMm_IsScene)
    soh/include/tables/nv_mm_entrance_table.h   per scene and start position, four entrances
                                                (OoT's child/adult x day/night setups; all four
                                                load the same spot, as RE1's do)

Numbers start after RE1's tables (NIGHTMAREVERSE.md, "Working in parallel"): RE1's last scene
is 0x10D and its last entrance 0xF63. Only scene names and start-position counts end up in the
headers (no MM data).

    python3 mm/tools/soh_tables.py <MM rom>
"""
import os
import struct
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import mm_rom  # noqa: E402
import yaz0  # noqa: E402
from mm2torch import commands  # noqa: E402
from mm_scene import soh_name  # noqa: E402

TABLES = os.path.join(HERE, "..", "..", "soh", "include", "tables")
FIRST_SCENE = 0x10E  # after RE1's SCENE_RE1_71C
FIRST_ENTRANCE = 0xF64  # after RE1's ENTR_RE1_71C_3_3


def spawn_count(rom, scene):
    _, _, ps, pe = rom.entry(scene)
    data = yaz0.decompress(rom.data[ps:pe])
    for cmd, n, _ in commands(data, 0):
        if cmd == 0x00:
            return n
    return 1


def main():
    rom = mm_rom.MMRom(sys.argv[1])
    head = "/* Generated by mm/tools/soh_tables.py: MM scenes (resources from the player's own MM ROM) */\n"
    S, E = [head], [head]
    entr = FIRST_ENTRANCE
    for i, scene in enumerate(mm_rom.CLOCK_TOWN):
        name = soh_name(scene)
        enum = "SCENE_" + name.upper()
        S.append(f"/* 0x{FIRST_SCENE + i:X} */ DEFINE_SCENE({name}_scene, none, {enum}, SDC_DEFAULT, 0, 0)\n")
        for spawn in range(spawn_count(rom, scene)):
            for layer in range(4):
                suffix = f"_{layer}" if layer else ""
                E.append(f"/* 0x{entr:X} */ DEFINE_ENTRANCE(ENTR_{name.upper()}_{spawn}{suffix}, {enum}, {spawn}, "
                         "false, true, TRANS_TYPE_FADE_BLACK, TRANS_TYPE_FADE_BLACK)\n")
                entr += 1
    open(os.path.join(TABLES, "nv_mm_scene_table.h"), "w").write("".join(S))
    open(os.path.join(TABLES, "nv_mm_entrance_table.h"), "w").write("".join(E))
    first = "SCENE_" + soh_name(list(mm_rom.CLOCK_TOWN)[0]).upper()
    last = "SCENE_" + soh_name(list(mm_rom.CLOCK_TOWN)[-1]).upper()
    open(os.path.join(TABLES, "nv_mm_scene_range.h"), "w").write(
        head + f"#define SCENE_MM_FIRST {first}\n#define SCENE_MM_LAST {last}\n")
    print(f"{len(S) - 1} scenes from 0x{FIRST_SCENE:X}, {entr - FIRST_ENTRANCE} entrances from 0x{FIRST_ENTRANCE:X}")


if __name__ == "__main__":
    main()
