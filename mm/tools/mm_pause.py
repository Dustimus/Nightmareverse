"""MM's pause-screen textures: every item and mask icon, every item name, and the page tiles of the
item and mask pages (and their English titles), for our MM pause pages (z_nv_mm_pause.c).

MM keeps most of these in "yar" archives (a table of offsets, then one Yaz0 block per texture; the
decomp's offsets are into the blocks decompressed one after another), which our converter (Torch)
can't read, so they're written here straight into the mod as libultraship textures (OTEX):
    mm/textures/<file>/<texture name>

Two steps, as the other MM tools:
    mm_pause.py <mm decomp>      reads the decomp's asset XMLs, writes mm_pause_textures.py (committed)
    write_textures(rom, res)     make_mod.py: the textures from the player's ROM, by that list
"""

import os
import re
import struct
import sys
import xml.etree.ElementTree as ET

sys.path.insert(0, os.path.dirname(__file__))

# MM's files (US 1.0 dmadata): the XML each is described by, and whether it's a yar archive
FILES = {
    19: ("archives/icon_item_static.xml", True),   # icon_item_static: icons, the pages' tiles
    17: ("archives/item_name_static.xml", True),   # item_name_static: the items' names
    13: ("interface/icon_item_jpn_static.xml", False),  # icon_item_jpn_static: the pages' English titles
}

OTEX = 0x4F544558  # libultraship ResourceType::Texture
FORMATS = {"rgba32": (1, 32), "rgba16": (2, 16), "i4": (5, 4), "i8": (6, 8), "ia4": (7, 4), "ia8": (8, 8),
           "ia16": (9, 16)}


def generate(decomp):
    rows = {}
    for index, (xml, _yar) in FILES.items():
        root = ET.parse(os.path.join(decomp, "assets", "xml", "N64_US", xml)).getroot()
        f = root.find("File")
        rows[index] = (f.attrib["Name"].replace("_yar", ""),
                       [(t.attrib["Name"], int(t.attrib["Offset"], 16), t.attrib["Format"].lower(),
                         int(t.attrib["Width"]), int(t.attrib["Height"])) for t in f.iter("Texture")])
    out = os.path.join(os.path.dirname(__file__), "mm_pause_textures.py")
    with open(out, "w") as fh:
        fh.write('"""Generated by mm_pause.py from the MM decomp\'s asset XMLs. Do not edit.\n'
                 'file index -> (name, [(texture, offset, format, width, height)])"""\n\nTEXTURES = {\n')
        for index, (name, texs) in rows.items():
            fh.write(f"    {index}: (\"{name}\", [\n")
            for t in texs:
                fh.write(f"        {t!r},\n")
            fh.write("    ]),\n")
        fh.write("}\n")
    print(out, sum(len(t) for _n, t in rows.values()), "textures")


def write_inc():
    """soh/src/code/nv_mm_pause.inc: per MM item id, its icon and its English name, as paths."""
    from mm_pause_textures import TEXTURES
    icons = [t[0] for t in TEXTURES[19][1]][:0x62]  # (the icons are in item id order, to the notebook)
    names = [t[0] for t in TEXTURES[17][1]]
    out = os.path.join(os.path.dirname(__file__), "..", "..", "soh", "src", "code", "nv_mm_pause.inc")
    with open(out, "w") as fh:
        fh.write("/* Generated by mm/tools/mm_pause.py from mm_pause_textures.py. Do not edit. */\n\n")
        fh.write("// per MM item id: its icon (MM's icon_item_static)\nstatic const char* sMmItemIcons[] = {\n")
        fh.writelines(f'    "__OTR__mm/textures/icon_item_static/{n}",\n' for n in icons)
        fh.write("};\n\n// per MM item id: its name (MM's item_name_static)\nstatic const char* sMmItemNames[] = {\n")
        fh.writelines(f'    "__OTR__mm/textures/item_name_static/{n}",\n' for n in names)
        fh.write("};\n")
    print(out)


def _file(rom, index):
    import yaz0
    vs, ve, ps, pe = rom.entry_index(index)
    raw = rom.data[ps:pe] if pe else rom.data[ps:ps + ve - vs]
    if FILES[index][1]:  # yar: block k at table size + offset k (block 0 right after the table)
        n = struct.unpack_from(">I", raw, 0)[0]
        offs = [0] + [struct.unpack_from(">I", raw, 4 * k)[0] for k in range(1, n // 4)]
        out = b""
        for o in offs:
            if raw[n + o:n + o + 4] != b"Yaz0":
                break
            out += yaz0.decompress(raw[n + o:])
        return out
    return yaz0.decompress(raw) if raw[:4] == b"Yaz0" else raw


def write_textures(rom, res):
    from mm_pause_textures import TEXTURES
    from mm_scene import _otr_header
    count = 0
    for index, (name, texs) in TEXTURES.items():
        data = _file(rom, index)
        d = os.path.join(res, "mm", "textures", name)
        os.makedirs(d, exist_ok=True)
        for tex, off, fmt, w, h in texs:
            kind, bpp = FORMATS[fmt]
            size = w * h * bpp // 8
            body = struct.pack("<IIII", kind, w, h, size) + data[off:off + size]
            open(os.path.join(d, tex), "wb").write(_otr_header(OTEX) + body)
            count += 1
            if tex == "gPauseMasks10ENGTex":
                _write_blank_top(res, data[off:off + size])
    print(f"MM pause textures: {count}")


def _write_blank_top(res, masks10):
    """Our own pages' top middle tile with no title (z_nv_gear.c): MM's mask page's (its corners carry
    no text), the title's rows (6-17, columns 14-74) filled from the band's own grain at that row's
    ends, blended left to right as the band's light falls off."""
    from mm_scene import _otr_header
    import random
    rng = random.Random(1)  # (the same tile every build)
    t = bytearray(masks10)
    for y in range(5, 19):
        row = masks10[y * 80:(y + 1) * 80]
        for x in range(14, 75):
            frac = (x - 14) / 60.0
            t[y * 80 + x] = row[rng.randrange(0, 14)] if rng.random() >= frac else row[rng.randrange(75, 80)]
    d = os.path.join(res, "mm", "textures", "nv_pause")
    os.makedirs(d, exist_ok=True)
    body = struct.pack("<IIII", FORMATS["ia8"][0], 80, 32, len(t)) + bytes(t)
    open(os.path.join(d, "gNvPauseBlankTop10Tex"), "wb").write(_otr_header(OTEX) + body)


if __name__ == "__main__":
    generate(sys.argv[1])
    write_inc()
