#!/usr/bin/env python3
"""Register converted RE1 rooms with Ship of Harkinian's scene and entrance tables.

Reads the scenes soh_scene.py wrote (scenes/shared/re1_<room>_scene/...) and writes the two
X-macro fragments that soh/include/tables/scene_table.h and entrance_table.h include after
OoT's own entries:

    soh/include/tables/nv_re1_scene_table.h      one DEFINE_SCENE per room
    soh/include/tables/nv_re1_entrance_table.h   per room and start position, four entrances
                                                 (OoT's child/adult x day/night setups; all
                                                 four load the same room)

Only room numbers and start-position counts end up in the headers (no RE1 data).

    python3 re1/tools/soh_tables.py <soh folder>   # e.g. the --soh folder of rdt2scene.py
"""
import argparse
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
TABLES = os.path.join(HERE, "..", "..", "soh", "include", "tables")
FIRST_SCENE = 0x6E  # after OoT's SCENE_TESTROOM
FIRST_ENTRANCE = 0x614  # after OoT's ENTR_DESERT_COLOSSUS_8_3


def rooms(folder):
    """[(name, start position count)] for every re1_* scene, by room number."""
    shared = os.path.join(folder, "scenes", "shared")
    out = []
    for d in sorted(os.listdir(shared)):
        m = re.match(r"(re1_[0-9a-f]{3})_scene$", d)
        if not m:
            continue
        xml = open(os.path.join(shared, d, d)).read()
        out.append((m.group(1), len(re.findall(r"<StartPositionEntry\b", xml))))
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("soh", help="folder with scenes/shared/re1_*_scene (rdt2scene.py --soh)")
    a = ap.parse_args()
    rs = rooms(a.soh)
    if not rs:
        sys.exit("no re1_* scenes in %s" % a.soh)

    head = "/* Generated by re1/tools/soh_tables.py: RE1 rooms (resources from the player's own RE1 files) */\n"
    sc = [head]
    en = [head]
    entr = FIRST_ENTRANCE
    for i, (name, nspawn) in enumerate(rs):
        enum = name.upper()
        sc.append("/* 0x%02X */ DEFINE_SCENE(%s_scene, none, SCENE_%s, SDC_DEFAULT, 0, 0)\n"
                  % (FIRST_SCENE + i, name, enum))
        for s in range(nspawn):
            for setup in range(4):
                suffix = "" if setup == 0 else "_%d" % setup
                en.append("/* 0x%03X */ DEFINE_ENTRANCE(ENTR_%s_%d%s, SCENE_%s, %d, false, true, "
                          "TRANS_TYPE_FADE_BLACK, TRANS_TYPE_FADE_BLACK)\n" % (entr, enum, s, suffix, enum, s))
                entr += 1
        print("%s: scene 0x%02X, entrance 0x%03X (%d start positions)"
              % (name, FIRST_SCENE + i, entr - 4 * nspawn, nspawn))
    open(os.path.join(TABLES, "nv_re1_scene_table.h"), "w").write("".join(sc))
    open(os.path.join(TABLES, "nv_re1_entrance_table.h"), "w").write("".join(en))


if __name__ == "__main__":
    main()
